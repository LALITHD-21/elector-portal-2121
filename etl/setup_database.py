def execute_sql_via_httpx(sql_statements):
    """Execute raw SQL via Supabase's /pg endpoint (requires service role)."""
    combined_sql = "\n".join(sql_statements)

    ctx = ssl.create_default_context()

    url = f"{SUPABASE_URL}/pg"
    headers = {
        "apikey": SERVICE_ROLE_KEY,
        "Authorization": f"Bearer {SERVICE_ROLE_KEY}",
        "Content-Type": "application/json",
    }
    data = json.dumps({"query": combined_sql}).encode()
    req = urllib.request.Request(url, data=data, headers=headers, method="POST")
    try:
        resp = urllib.request.urlopen(req, context=ctx)
        print(f"  /pg endpoint OK: HTTP {resp.status}")
        body = resp.read().decode()
        print(f"  Response: {body[:300]}")
        return True
    except Exception as e:
        print(f"  /pg endpoint not available: {e}")
        return False


